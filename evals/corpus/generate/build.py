"""Build the corpus and its manifest (Story 1.7).

    python -m generate                      # (re)build build/ and write manifest.yaml
    python -m generate --check              # build, fail if manifest.yaml would change

Run from ``evals/corpus`` with the backend environment:
``uv run --project ../../backend python -m generate``.
"""

import argparse
import difflib
import hashlib
import shutil
import sys
from pathlib import Path
from typing import Final

import yaml  # type: ignore[import-untyped]

from generate.content import SECTORS, SEED, WARNING, DocRecord, Injections, make_company
from generate.docx_docs import apply_diffs, build_spa, build_term_sheet, term_sheet_v3
from generate.financials import make_financials
from generate.manifest_schema import DocumentEntry, Manifest, WorkbookTotal
from generate.pdf_cim import CimSpec, build_cim
from generate.pdf_scanned import build_kyc_scan, build_resolution_scan
from generate.pptx_deck import build_deck
from generate.xlsx_books import (
    build_budget_workbook,
    build_model_workbook,
    build_transactions_workbook,
    build_vendor_csv,
)

CORPUS_DIR: Final = Path(__file__).resolve().parents[1]
DEFAULT_OUT: Final = CORPUS_DIR / "build"
DEFAULT_MANIFEST: Final = CORPUS_DIR / "manifest.yaml"

CIMS: Final = (
    CimSpec("cim_project_alpha_vardhan_chemicals.pdf", "Alpha", 60, metadata_injection=True),
    CimSpec("cim_project_bodhi_sahyadri_healthcare.pdf", "Bodhi", 110, metadata_injection=False),
    CimSpec("cim_project_chakra_nilgiri_logistics.pdf", "Chakra", 150, metadata_injection=False),
)
BASE_REVENUE_CR: Final = (900, 1400, 2200)


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def generate(out: Path) -> Manifest:
    """Generate every document into ``out`` (emptied first) and return the manifest."""
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    o = str(out)
    companies = [make_company(i, SECTORS[i], listed=i != 1) for i in range(3)]
    fins = [make_financials(c, base) for c, base in zip(companies, BASE_REVENUE_CR, strict=True)]
    injections = Injections()
    records: list[DocRecord] = []
    totals: list[WorkbookTotal] = []

    for k, spec in enumerate(CIMS):
        records.append(build_cim(o, spec, companies[k], fins[k], injections, k))
    v3 = term_sheet_v3(companies[0], "Halcyon Growth Partners Fund III")
    v4, diff = apply_diffs(v3)
    records.append(build_term_sheet(o, "term_sheet_v3.docx", 3, v3, companies[0], injections))
    records.append(build_term_sheet(o, "term_sheet_v4.docx", 4, v4, companies[0], injections))
    records.append(build_spa(o, "spa_vardhan_chemicals.docx", companies[0], injections))
    records.append(
        build_deck(o, "management_presentation_sahyadri.pptx", companies[1], fins[1], injections)
    )
    for builder, file, k in (
        (build_model_workbook, "model_vardhan_chemicals.xlsx", 0),
        (build_budget_workbook, "budget_sahyadri_healthcare.xlsx", 1),
        (build_transactions_workbook, "invoices_nilgiri_logistics.xlsx", 2),
    ):
        rec, wb_totals = builder(o, file, companies[k], fins[k], injections)
        records.append(rec)
        totals.extend(wb_totals)
    records.append(build_vendor_csv(o, "vendor_ledger_nilgiri.csv", companies[2]))
    records.append(build_kyc_scan(o, "scan_kyc_form.pdf", companies[1]))
    records.append(build_resolution_scan(o, "scan_board_resolution.pdf", companies[2]))

    documents = [
        DocumentEntry(
            file=r.file,
            format=r.format,
            title=r.title,
            sha256=_sha256(out / r.file),
            bytes=(out / r.file).stat().st_size,
            pages=r.pages,
            slides=r.slides,
            sheets=r.sheets,
            hidden_sheets=r.hidden_sheets,
            rows=r.rows,
            image_only=r.image_only,
            canary=r.canary,
            key_terms=r.key_terms,
            figures=r.figures,
            uncached_formulas=r.uncached_formulas,
        )
        for r in records
    ]
    return Manifest(
        seed=SEED,
        warning=WARNING,
        documents=documents,
        items=[item for r in records for item in r.items],
        term_sheet_diff=diff,
        workbook_totals=totals,
    )


def dump(manifest: Manifest) -> str:
    header = (
        "# Synthetic corpus manifest (Story 1.7). GENERATED by `make corpus`; do not edit.\n"
        "# Every person, company, deal and identifier here is fabricated.\n"
    )
    body = yaml.safe_dump(
        manifest.model_dump(mode="json", exclude_defaults=True),
        sort_keys=False,
        allow_unicode=True,
        width=120,
    )
    return header + str(body)


def load(path: Path) -> Manifest:
    return Manifest.model_validate(yaml.safe_load(path.read_text(encoding="utf-8")))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m generate", description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--check", action="store_true", help="fail if the manifest would change")
    args = parser.parse_args(argv)

    text = dump(generate(args.out))
    if args.check:
        current = args.manifest.read_text(encoding="utf-8") if args.manifest.exists() else ""
        if current != text:
            diff = difflib.unified_diff(
                current.splitlines(), text.splitlines(), "committed", "generated", lineterm=""
            )
            print("\n".join(list(diff)[:60]), file=sys.stderr)
            print("manifest.yaml is out of date or the build is not deterministic", file=sys.stderr)
            return 1
        print(f"corpus OK: {args.out} matches {args.manifest}")
        return 0
    args.manifest.write_text(text, encoding="utf-8")
    print(f"wrote {len(list(args.out.iterdir()))} files to {args.out} and {args.manifest}")
    return 0
